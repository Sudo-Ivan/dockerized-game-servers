#!/bin/sh
# Resolve image matrix rows for CI.
# Prints one TSV line per image: name context containerfile base_name_or_empty

set -eu

emit() {
  name="$1"
  context="$2"
  containerfile="$3"
  base="${4:-}"
  printf '%s\t%s\t%s\t%s\n' "${name}" "${context}" "${containerfile}" "${base}"
}

