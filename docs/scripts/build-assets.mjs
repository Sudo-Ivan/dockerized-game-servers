#!/usr/bin/env node
import { createHash } from 'node:crypto'
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { zipSync, strToU8 } from 'fflate'
import { resolveRepo } from '../src/lib/repo.mjs'
import { buildSearchIndex } from '../src/lib/search-index.mjs'
import { fetchGameIcons } from './fetch-game-icons.mjs'

const docsDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const contentRoot = path.join(docsDir, 'src/content/docs')
const publicDir = path.join(docsDir, 'public')
mkdirSync(publicDir, { recursive: true })

const repo = resolveRepo()
const tokens = {
	'{{IMAGE_PREFIX}}': repo.imagePrefix,
	'{{GITHUB_URL}}': repo.githubUrl,
	'{{DOCS_URL}}': repo.docsUrl,
	'{{REPO}}': repo.repo,
	'{{IMAGE_OWNER}}': repo.imageOwner,
}

function applyTokens(text) {
	let next = text
	for (const [token, replacement] of Object.entries(tokens)) {
		next = next.split(token).join(replacement)
	}
	return next
}

function walkMarkdown(dir, files = []) {
	for (const name of readdirSync(dir)) {
		const full = path.join(dir, name)
		const st = statSync(full)
		if (st.isDirectory()) {
			walkMarkdown(full, files)
			continue
		}
		if (name.endsWith('.md') || name.endsWith('.mdx')) files.push(full)
	}
	return files
}

function buildDocsZip() {
	/** @type {Record<string, Uint8Array>} */
	const entries = {}
	for (const file of walkMarkdown(contentRoot).sort()) {
		const rel = path.relative(contentRoot, file).split(path.sep).join('/')
		if (
			rel === '404.md' ||
			rel === 'offline.md' ||
			rel === 'error.md' ||
			rel === 'gone.md'
		) {
			continue
		}
		entries[`docs/${rel}`] = strToU8(applyTokens(readFileSync(file, 'utf8')))
	}
	entries['README.txt'] = strToU8(
		[
			'Dockerized Game Servers documentation export',
			`Repository: ${repo.repo}`,
			`Generated: ${new Date().toISOString()}`,
			'License: 0BSD',
			'',
		].join('\n'),
	)
	const zipped = zipSync(entries, { level: 6 })
	writeFileSync(path.join(publicDir, 'dgs-docs.zip'), zipped)
	return Object.keys(entries).length
}

function buildSiteModule() {
	const generatedDir = path.join(docsDir, 'src/generated')
	mkdirSync(generatedDir, { recursive: true })
	const body = `/** Generated by scripts/build-assets.mjs. Do not edit. */
export const site = ${JSON.stringify(
		{
			repo: repo.repo,
			owner: repo.owner,
			name: repo.name,
			githubUrl: repo.githubUrl,
			siteUrl: repo.siteUrl,
			siteBase: repo.siteBase,
			docsUrl: repo.docsUrl,
			imagePrefix: repo.imagePrefix,
		},
		null,
		2,
	)}
`
	writeFileSync(path.join(generatedDir, 'site.mjs'), body)
}

function buildRobotsTxt() {
	const base = repo.siteBase.endsWith('/') ? repo.siteBase : `${repo.siteBase}/`
	const sitemap = `${repo.siteUrl}${base}sitemap-index.xml`
	const body = [
		'User-agent: *',
		'Allow: /',
		'',
		`Sitemap: ${sitemap}`,
		'',
	].join('\n')
	writeFileSync(path.join(publicDir, 'robots.txt'), body)
}

function buildSearch() {
	const index = buildSearchIndex()
	writeFileSync(path.join(publicDir, 'search-index.json'), `${JSON.stringify(index)}\n`)
	return index.documents.length
}

function buildManifestAndSw(buildId) {
	const base = repo.siteBase.endsWith('/') ? repo.siteBase : `${repo.siteBase}/`
	const scope = base
	const startUrl = base
	const offlineUrl = `${base}offline/`

	const manifest = {
		name: 'Dockerized Game Servers',
		short_name: 'Game Servers',
		description: 'Dockerized dedicated game servers with small images and compose files.',
		id: base,
		lang: 'en',
		start_url: startUrl,
		scope,
		display: 'standalone',
		background_color: '#0a0a0a',
		theme_color: '#0a0a0a',
		icons: [
			{
				src: `${base}icon.svg`,
				sizes: 'any',
				type: 'image/svg+xml',
				purpose: 'any',
			},
			{
				src: `${base}icon.svg`,
				sizes: 'any',
				type: 'image/svg+xml',
				purpose: 'maskable',
			},
		],
	}
	writeFileSync(path.join(publicDir, 'manifest.webmanifest'), `${JSON.stringify(manifest, null, 2)}\n`)

	const sw = `/* generated ${buildId} - do not edit */
const BUILD_ID = ${JSON.stringify(buildId)}
const ASSET_CACHE = 'dgs-assets-' + BUILD_ID
const DOC_CACHE = 'dgs-docs-' + BUILD_ID
const OFFLINE_URL = ${JSON.stringify(offlineUrl)}
const SCOPE = ${JSON.stringify(scope)}

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(DOC_CACHE)
    try {
      await cache.add(OFFLINE_URL)
    } catch (_) {}
    await self.skipWaiting()
  })())
})

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys()
    await Promise.all(
      keys
        .filter((key) => key !== ASSET_CACHE && key !== DOC_CACHE)
        .map((key) => caches.delete(key)),
    )
    await self.clients.claim()
    const clients = await self.clients.matchAll({ type: 'window' })
    for (const client of clients) {
      client.postMessage({ type: 'DGS_SW_ACTIVATED', buildId: BUILD_ID })
    }
  })())
})

async function networkFirst(request, cacheName, fallbackUrl) {
  const cache = await caches.open(cacheName)
  try {
    const fresh = await fetch(request)
    if (fresh.ok) {
      await cache.put(request, fresh.clone())
    }
    return fresh
  } catch (error) {
    const cached = await cache.match(request)
    if (cached) return cached
    if (fallbackUrl) {
      const offline = await cache.match(fallbackUrl)
      if (offline) return offline
    }
    throw error
  }
}

async function staleWhileRevalidate(request, cacheName) {
  const cache = await caches.open(cacheName)
  const cached = await cache.match(request)
  const networkPromise = fetch(request)
    .then(async (response) => {
      if (response.ok) await cache.put(request, response.clone())
      return response
    })
    .catch(() => cached)
  return cached || networkPromise
}

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return
  if (!url.pathname.startsWith(SCOPE)) return

  const isNavigate = request.mode === 'navigate'
  const isHtml = isNavigate || url.pathname.endsWith('.html') || url.pathname.endsWith('/')
  const isDocsData =
    url.pathname.endsWith('/search-index.json') ||
    url.pathname.endsWith('/dgs-docs.zip') ||
    url.pathname.endsWith('/manifest.webmanifest')

  if (isHtml || isDocsData) {
    event.respondWith(networkFirst(request, DOC_CACHE, isNavigate ? OFFLINE_URL : undefined))
    return
  }

  if (url.pathname.includes('/_astro/') || /\\.(?:js|css|svg|woff2?)$/.test(url.pathname)) {
    event.respondWith(staleWhileRevalidate(request, ASSET_CACHE))
  }
})

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'DGS_SKIP_WAITING') {
    self.skipWaiting()
  }
})
`
	writeFileSync(path.join(publicDir, 'sw.js'), sw)
}

const stampSource = [
	...walkMarkdown(contentRoot).map((file) => readFileSync(file)),
	readFileSync(path.join(docsDir, 'package.json')),
	Buffer.from(repo.repo),
].reduce((acc, buf) => {
	acc.update(buf)
	return acc
}, createHash('sha256'))
const buildId = stampSource.digest('hex').slice(0, 16)

buildSiteModule()
buildRobotsTxt()
const docsCount = buildDocsZip()
const searchCount = buildSearch()
buildManifestAndSw(buildId)
const { icons: gameIcons, report: iconReport } = await fetchGameIcons()

console.log(
	`docs assets: zip=${docsCount} files, search=${searchCount} docs, icons=${Object.keys(gameIcons).length}/${iconReport.length}, buildId=${buildId}, base=${repo.siteBase}`,
)
